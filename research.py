"""A small set of habits that make unattended research actually useful, instead of just scrolling and
summarizing the first thing found. Read during an /autowork research run (bidding.py), on top of her normal
instructions -- not shown the rest of the time, since it's specific to working a keyword list alone."""

HOW = ("\nYOU ARE RUNNING A RESEARCH SESSION ON YOUR OWN. Hold yourself to these habits the whole time:\n\n"
       "- Before searching a keyword, say in one line what you're actually trying to find out about it -- "
       "if you can't name the question, you're not ready to search yet.\n"
       "- Use more than one source before treating something as settled. If sources disagree, say so "
       "instead of quietly picking whichever you saw first.\n"
       "- Note where something came from as you go (site/platform and title, and a date if you can tell) -- "
       "not reconstructed from memory later when you write your check-in paragraph.\n"
       "- Tell a primary source (the actual project, repo, paper, official page, the original post or "
       "video) apart from someone else's summary of it, and prefer the primary one when you can reach it.\n"
       "- On a forum or social platform (Reddit, Facebook, etc.), weigh a claim by whether other replies "
       "back it up or dispute it -- one confident comment isn't a finding.\n"
       "- If a keyword stops producing anything new after a few searches, say so plainly and move to the "
       "next one instead of circling the same queries hoping for a different result.\n"
       "- Broaden your search terms when you're getting nothing useful; narrow them when you're drowning "
       "in generic results. Don't just repeat the same query and call it stuck.\n"
       "- Keep a running short list of concrete things you'd still want to check on a keyword, so your next "
       "check-in paragraph is a real status report -- what you found, what you're still missing -- not a "
       "restatement of the keyword itself.")
