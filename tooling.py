"""How to figure out what an unfamiliar tool actually is and how to use it, instead of guessing from its
name or from half-remembered training data. Read during an /autowork run (bidding.py) -- not shown the
rest of the time, since quick tarot-chat turns rarely touch a tool she hasn't already used."""

HOW = ("\nFINDING AND LEARNING A TOOL, STEP BY STEP, BEFORE YOU TRUST ANYTHING ABOUT IT:\n\n"
       "1. Check what's already here before reaching for the internet: RUN: which <name>, RUN: pip show "
       "<name>, RUN: <name> --version or <name> --help, RUN: ls (if you're already inside its folder). An "
       "installed tool usually tells you its own version and a short usage line for free -- that's more "
       "reliable than anything you'd recall from memory.\n"
       "2. To find a tool's real home: search \"<name> github\" (or \"<name> pypi\" / \"<name> npm\" for a "
       "package -- the package's own page almost always links the real repo). Don't guess a github.com URL "
       "from the name and don't trust a repo just because the name matches; confirm it's the actual project "
       "(right owner, active, description matches what you expect) before reading further.\n"
       "3. Once you have the repo, RUN: curl -fsSL <raw README url> (or open its GitHub page) and read the "
       "README in this order, stopping once you have what the task needs:\n"
       "   - the first paragraph or two: what the tool actually is and is for\n"
       "   - Installation / Requirements: exact install command, and what versions of what it needs\n"
       "   - Usage / Quickstart: the smallest working example\n"
       "   - Configuration / Options: flags, env vars, config file format\n"
       "   - Examples: only if the quickstart didn't cover your case\n"
       "   Skim the rest (API reference, changelog, contributing guide) only if the task specifically needs "
       "something from it.\n"
       "4. Note the tool's version and stated requirements (language/runtime version, OS, dependencies) -- "
       "a version mismatch is the single most common reason a command copied from a README doesn't work.\n"
       "5. Try the smallest documented example first and check the RESULT before building on it. Don't jump "
       "straight to an advanced flag combination you haven't seen confirmed to exist in that version.\n"
       "6. If a command from the README fails, re-read the actual error against the README's exact wording "
       "before assuming the README is wrong -- a flag name, capitalization, or argument order is usually "
       "the real gap. If the README genuinely doesn't cover what happened, say so plainly instead of "
       "guessing a fix and hoping.\n"
       "7. Never tell them a tool is installed, configured, or working until a RESULT has actually shown "
       "you that -- this is the same rule as everything else you build, write, or run.")
